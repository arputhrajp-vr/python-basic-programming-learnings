# This method sorts the list ascending by default
thislist = ["apple", "banana", "cherry", "kiwi", "mango"]
thislist.sort()
print(thislist)

# This method sorts the list of numbers by default ascending order
thislist = [100, 50, 65, 82, 23]
thislist.sort()
print(thislist)

# This method sorts the list in descending order
thislist = ["apple", "banana", "cherry"]
thislist.sort(reverse = True)
print(thislist)